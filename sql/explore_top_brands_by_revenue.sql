-- Top 10 brands by revenue per currency (COMPLETED orders only)
SELECT v.CURRENCY, p.BRAND, SUM(v.LINE_AMOUNT) revenue, COUNT(DISTINCT v.ORDER_ID) orders, SUM(v.QUANTITY) units,
RANK() OVER (PARTITION BY v.CURRENCY ORDER BY SUM(v.LINE_AMOUNT) DESC) rnk
FROM COCO_ANALYST.MY_TABLE.V_VALID_ORDER_LINES v
JOIN COCO_ANALYST.MY_TABLE.DIM_PRODUCTS p ON p.PRODUCT_ID = v.PRODUCT_ID
GROUP BY 1,2 QUALIFY rnk <= 10 ORDER BY 1, rnk;

-- Context: currencies, brand count, join coverage
SELECT v.CURRENCY, COUNT(*) lines, COUNT(p.PRODUCT_ID) matched_lines, COUNT(DISTINCT p.BRAND) brands, SUM(v.LINE_AMOUNT) revenue,
(SELECT COUNT(DISTINCT CURRENCY) FROM COCO_ANALYST.MY_TABLE.FCT_ORDER_LINES) currencies_all_status,
COUNT_IF(p.CURRENCY <> v.CURRENCY) product_currency_mismatch
FROM COCO_ANALYST.MY_TABLE.V_VALID_ORDER_LINES v
LEFT JOIN COCO_ANALYST.MY_TABLE.DIM_PRODUCTS p ON p.PRODUCT_ID = v.PRODUCT_ID
GROUP BY 1;
