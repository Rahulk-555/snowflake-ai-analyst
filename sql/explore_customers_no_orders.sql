-- Customers with no valid (COMPLETED) orders: counts
SELECT
  COUNT(*) AS total_customers,
  COUNT_IF(NOT EXISTS (SELECT 1 FROM COCO_ANALYST.MY_TABLE.V_VALID_ORDER_LINES v WHERE v.CUSTOMER_ID = c.CUSTOMER_ID)) AS no_valid_orders,
  COUNT_IF(NOT EXISTS (SELECT 1 FROM COCO_ANALYST.MY_TABLE.FCT_ORDER_LINES f WHERE f.CUSTOMER_ID = c.CUSTOMER_ID)) AS no_orders_any_status
FROM COCO_ANALYST.MY_TABLE.DIM_CUSTOMERS c;

-- List (CUSTOMER_ID only, no PII)
SELECT c.CUSTOMER_ID, c.COUNTRY, c.SUBSCRIPTION_DATE
FROM COCO_ANALYST.MY_TABLE.DIM_CUSTOMERS c
LEFT JOIN (SELECT DISTINCT CUSTOMER_ID FROM COCO_ANALYST.MY_TABLE.V_VALID_ORDER_LINES) v
  ON v.CUSTOMER_ID = c.CUSTOMER_ID
WHERE v.CUSTOMER_ID IS NULL
ORDER BY c.SUBSCRIPTION_DATE
LIMIT 20;
