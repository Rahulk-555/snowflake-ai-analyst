-- profile-table: DIM_CUSTOMERS
DESCRIBE TABLE COCO_ANALYST.MY_TABLE.DIM_CUSTOMERS;

-- Keys, nulls/blanks, date checks, formats
SELECT COUNT(*) n, COUNT(DISTINCT CUSTOMER_ID) d_id, COUNT(DISTINCT LOWER(TRIM(CUSTOMER_ID))) d_id_norm, COUNT(DISTINCT INDEX) d_index,
COUNT(DISTINCT LOWER(EMAIL)) d_email,
COUNT_IF(CUSTOMER_ID IS NULL OR TRIM(CUSTOMER_ID)='') id_null,
COUNT_IF(FIRST_NAME IS NULL OR TRIM(FIRST_NAME)='') fn_null, COUNT_IF(LAST_NAME IS NULL OR TRIM(LAST_NAME)='') ln_null,
COUNT_IF(COMPANY IS NULL OR TRIM(COMPANY)='') co_null, COUNT_IF(CITY IS NULL OR TRIM(CITY)='') city_null,
COUNT_IF(COUNTRY IS NULL OR TRIM(COUNTRY)='') ctry_null, COUNT_IF(PHONE_1 IS NULL OR TRIM(PHONE_1)='') p1_null,
COUNT_IF(PHONE_2 IS NULL OR TRIM(PHONE_2)='') p2_null, COUNT_IF(EMAIL IS NULL OR TRIM(EMAIL)='') email_null,
COUNT_IF(WEBSITE IS NULL OR TRIM(WEBSITE)='') web_null, COUNT_IF(SUBSCRIPTION_DATE IS NULL) sub_null,
COUNT_IF(INDEX IS NULL) idx_null,
MIN(SUBSCRIPTION_DATE) min_sub, MAX(SUBSCRIPTION_DATE) max_sub,
COUNT_IF(SUBSCRIPTION_DATE > CURRENT_DATE()) future_sub, COUNT_IF(SUBSCRIPTION_DATE < '2000-01-01') ancient_sub,
COUNT_IF(DAYOFWEEK(SUBSCRIPTION_DATE) IN (0,6)) weekend_sub,
COUNT_IF(EMAIL NOT RLIKE '^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$') bad_email,
COUNT_IF(CUSTOMER_ID <> TRIM(CUSTOMER_ID) OR CITY <> TRIM(CITY) OR COUNTRY <> TRIM(COUNTRY)) untrimmed,
MIN(LENGTH(CUSTOMER_ID)) min_len, MAX(LENGTH(CUSTOMER_ID)) max_len, MIN(INDEX) min_idx, MAX(INDEX) max_idx
FROM COCO_ANALYST.MY_TABLE.DIM_CUSTOMERS;

-- Subscriptions by year
SELECT YEAR(SUBSCRIPTION_DATE) yr, COUNT(*) n, COUNT(DISTINCT SUBSCRIPTION_DATE) days, MIN(SUBSCRIPTION_DATE) mn, MAX(SUBSCRIPTION_DATE) mx
FROM COCO_ANALYST.MY_TABLE.DIM_CUSTOMERS GROUP BY 1 ORDER BY 1;

-- Top 10 COUNTRY / CITY
SELECT 'COUNTRY' col, COUNTRY val, COUNT(*) n, (SELECT COUNT(DISTINCT COUNTRY) FROM COCO_ANALYST.MY_TABLE.DIM_CUSTOMERS) distinct_vals FROM COCO_ANALYST.MY_TABLE.DIM_CUSTOMERS GROUP BY 2 QUALIFY ROW_NUMBER() OVER (ORDER BY n DESC)<=10
UNION ALL
SELECT 'CITY', CITY, COUNT(*), (SELECT COUNT(DISTINCT CITY) FROM COCO_ANALYST.MY_TABLE.DIM_CUSTOMERS) FROM COCO_ANALYST.MY_TABLE.DIM_CUSTOMERS GROUP BY 2 QUALIFY ROW_NUMBER() OVER (ORDER BY COUNT(*) DESC)<=10
ORDER BY col, n DESC;

-- Cross-check with orders (all statuses)
WITH f AS (SELECT CUSTOMER_ID, MIN(ORDER_DATE) first_order FROM COCO_ANALYST.MY_TABLE.FCT_ORDER_LINES GROUP BY 1)
SELECT COUNT(*) customers_with_orders, COUNT_IF(c.CUSTOMER_ID IS NULL) orphan_order_customers,
COUNT_IF(f.first_order < c.SUBSCRIPTION_DATE) ordered_before_subscribing,
MIN(DATEDIFF('day', c.SUBSCRIPTION_DATE, f.first_order)) min_days_sub_to_order
FROM f LEFT JOIN COCO_ANALYST.MY_TABLE.DIM_CUSTOMERS c ON c.CUSTOMER_ID = f.CUSTOMER_ID;

-- Consistency / format checks (aggregated, no PII output)
SELECT
(SELECT COUNT(DISTINCT COUNTRY) - COUNT(DISTINCT LOWER(COUNTRY)) FROM COCO_ANALYST.MY_TABLE.DIM_CUSTOMERS) country_case_variants,
(SELECT COUNT(DISTINCT CITY) - COUNT(DISTINCT LOWER(CITY)) FROM COCO_ANALYST.MY_TABLE.DIM_CUSTOMERS) city_case_variants,
(SELECT COUNT_IF(PHONE_1 RLIKE '.*x[0-9]+.*') FROM COCO_ANALYST.MY_TABLE.DIM_CUSTOMERS) phone1_with_extension,
(SELECT COUNT(DISTINCT REGEXP_REPLACE(PHONE_1,'[0-9]','9')) FROM COCO_ANALYST.MY_TABLE.DIM_CUSTOMERS) phone1_format_patterns,
(SELECT COUNT_IF(PHONE_1 = PHONE_2) FROM COCO_ANALYST.MY_TABLE.DIM_CUSTOMERS) phone1_eq_phone2,
(SELECT COUNT_IF(WEBSITE NOT ILIKE 'http%') FROM COCO_ANALYST.MY_TABLE.DIM_CUSTOMERS) website_no_scheme,
(SELECT COUNT(*) FROM (SELECT FIRST_NAME, LAST_NAME, COMPANY FROM COCO_ANALYST.MY_TABLE.DIM_CUSTOMERS GROUP BY 1,2,3 HAVING COUNT(*)>1)) dup_name_company_groups;
