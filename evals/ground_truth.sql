-- GT1: total customers vs customers with valid orders
SELECT (SELECT COUNT(*) FROM COCO_ANALYST.MY_TABLE.DIM_CUSTOMERS) AS TOTAL_CUSTOMERS,
       (SELECT COUNT(DISTINCT CUSTOMER_ID) FROM COCO_ANALYST.MY_TABLE.V_VALID_ORDER_LINES) AS CUSTOMERS_WITH_ORDERS;

-- GT2: valid revenue by currency
SELECT CURRENCY, SUM(LINE_AMOUNT) AS REVENUE
FROM COCO_ANALYST.MY_TABLE.V_VALID_ORDER_LINES GROUP BY 1 ORDER BY 1;

-- GT3: average orders per customer (customers with at least one valid order)
SELECT AVG(ORDERS) FROM (
  SELECT CUSTOMER_ID, COUNT(DISTINCT ORDER_ID) AS ORDERS
  FROM COCO_ANALYST.MY_TABLE.V_VALID_ORDER_LINES GROUP BY 1);

-- GT4: churned = had a valid order, but none in the last 90 days
SELECT COUNT(*) FROM (
  SELECT CUSTOMER_ID FROM COCO_ANALYST.MY_TABLE.V_VALID_ORDER_LINES
  GROUP BY 1 HAVING MAX(ORDER_DATE) < DATEADD(day, -90, CURRENT_DATE()));